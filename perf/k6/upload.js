import http from 'k6/http'
import { check, fail } from 'k6'

// Load test on POST /api/files, the endpoint the whole 1 GB transits through
// (see docs/architectureDecisions/tech_stack.md, "Transit des fichiers": the
// upload goes through the API, only the download uses a presigned URL).
//
// One payload size per run, driven by PAYLOAD and VUS. k6 holds the request
// body in memory, so opening the four sizes at once would make the runner,
// not the server, the thing being measured. The Makefile chains the steps.

const API_URL = __ENV.API_URL || 'http://localhost:8080'
const PAYLOAD = __ENV.PAYLOAD || '10M'
const VUS = Number(__ENV.VUS || 1)
const ITERATIONS = Number(__ENV.ITERATIONS || 1)

// Well above nginx's fastcgi_read_timeout (300s): a request that gives up
// before the server does would be recorded as a client failure and hide the
// actual limit.
const UPLOAD_TIMEOUT = '600s'

// Read once per VU at init time, from the files generated by "make fixtures".
const payload = open(`../fixtures/payload-${PAYLOAD}.bin`, 'b')

const ACCOUNT_PASSWORD = 'Perf-Load-Test-Passphrase-2026!'
const JSON_HEADERS = { 'Content-Type': 'application/json' }

export const options = {
  scenarios: {
    upload: {
      // Every VU sends the same number of files, so the sizes stay comparable
      // from one step to the next; a duration-driven executor would send more
      // small files than large ones.
      executor: 'per-vu-iterations',
      vus: VUS,
      iterations: ITERATIONS,
      maxDuration: '30m',
    },
  },
  thresholds: {
    checks: ['rate==1.00'],
    http_req_failed: ['rate==0.00'],
  },
  // Stamps every metric with the step it belongs to, so the four JSON outputs
  // can be read side by side. Requests carry a "name" tag on top of it, which
  // keeps the uploads apart from the login and the cleanup.
  tags: { payload: PAYLOAD },
}

/**
 * Registers a throwaway account and signs it in. The test therefore measures
 * the real authenticated path (US01) and needs no manual preparation; the
 * account also scopes the cleanup, since GET /api/files only ever returns its
 * owner's uploads.
 */
export function setup() {
  const email = `perf-${Date.now()}@datashare.test`

  const registration = http.post(
    `${API_URL}/api/register`,
    JSON.stringify({
      email,
      firstName: 'Perf',
      lastName: 'Runner',
      plainPassword: ACCOUNT_PASSWORD,
    }),
    { headers: JSON_HEADERS, tags: { name: 'setup:register' } },
  )
  if (registration.status !== 201) {
    fail(`registration failed with ${registration.status}: ${registration.body}`)
  }

  const login = http.post(
    `${API_URL}/api/login`,
    JSON.stringify({ email, password: ACCOUNT_PASSWORD }),
    { headers: JSON_HEADERS, tags: { name: 'setup:login' } },
  )
  if (login.status !== 200) {
    fail(`login failed with ${login.status}: ${login.body}`)
  }

  return { token: login.json('token'), email }
}

export default function (data) {
  const response = http.post(
    `${API_URL}/api/files`,
    {
      file: http.file(payload, `perf-${PAYLOAD}-${__VU}-${__ITER}.bin`, 'application/octet-stream'),
      // Shortest lifetime the contract accepts: these files are disposable,
      // and teardown deletes them anyway.
      expiresInDays: '1',
    },
    {
      headers: { Authorization: `Bearer ${data.token}` },
      timeout: UPLOAD_TIMEOUT,
      tags: { name: 'upload' },
    },
  )

  check(response, {
    'upload accepted (201)': (r) => r.status === 201,
    'download link returned': (r) => Boolean(r.json('downloadToken')),
  })
}

/**
 * Deletes everything the run uploaded. Without this, a full campaign leaves
 * several gigabytes behind in the object storage and in the file table.
 */
export function teardown(data) {
  const headers = { Authorization: `Bearer ${data.token}` }

  const history = http.get(`${API_URL}/api/files`, {
    headers,
    tags: { name: 'teardown:list' },
  })
  if (history.status !== 200) {
    console.warn(`cleanup skipped, history answered ${history.status}`)
    return
  }

  for (const file of history.json()) {
    const deletion = http.del(`${API_URL}/api/files/${file.id}`, null, {
      headers,
      timeout: UPLOAD_TIMEOUT,
      tags: { name: 'teardown:delete' },
    })
    if (deletion.status !== 204) {
      console.warn(`file ${file.id} not deleted, answered ${deletion.status}`)
    }
  }

  // The account itself has no delete route, by design: see perf/README.md for
  // the one-liner that clears the leftover rows.
  console.log(`test account left behind: ${data.email}`)
}
